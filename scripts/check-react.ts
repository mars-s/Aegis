import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { BoardSchema } from "@aegis/domain";
import type { TestFacade } from "../app/src/platform/test-facade.js";
import { withReactBrowser } from "./react-browser.ts";

const output = resolve(process.env.AEGIS_CHECK_OUT ?? "/tmp/aegis-react-check");
mkdirSync(output, { recursive: true });
const observations: string[] = [];
await withReactBrowser(async page => {
  const applied = await page.evaluate(() => {
    const facade: TestFacade | undefined = window.aegis;
    if (!facade) throw new Error("Missing test facade");
    return facade.apply([
      { op: "create", newId: "reactnote", type: "note", text: "Saved note", heading: "Drag this note", x: 200, y: 200, w: 280, h: 160 },
      { op: "create", newId: "reacttitle", type: "title", text: "React board", x: 200, y: 100, w: 340, h: 64 },
    ]);
  });
  assert.equal(applied.kind, "applied", "optimistic synchronous submission");
  if (applied.kind === "applied") assert.equal(applied.ids.length, 2, "created ids returned synchronously");
  await page.evaluate(async () => { await window.aegis?.flush(); });
  const note = page.locator('.card[data-id="reactnote"] .body');
  await note.waitFor();
  assert.equal(await note.innerText(), "Saved note");
  assert.equal(await page.locator('.card[data-id="reacttitle"] .body').innerText(), "React board");
  observations.push("note and title rendered through leases; optimistic created ids returned");
  const savedBoard = async () => BoardSchema.parse(await page.evaluate(async () => {
    const facade = window.aegis;
    if (!facade) throw new Error("Missing test facade");
    return facade.host.get(`/boards/${facade.canvas.board.id}`);
  }));
  await page.waitForTimeout(200);
  await page.evaluate(async () => { await window.aegis?.flush(); });
  const initial = await savedBoard();
  assert.equal(initial.rev, 1, "mounting notes does not create ignored measurement transactions");
  const noteBefore = initial.cards.find(card => card.id === "reactnote");
  assert.ok(noteBefore);
  await page.mouse.move(900, 500);
  const panBefore = await page.evaluate(() => window.aegis?.canvas.view);
  assert.ok(panBefore);
  await page.mouse.wheel(140, 80);
  await page.waitForTimeout(700);
  const panned = await page.evaluate(() => window.aegis?.canvas.view);
  assert.ok(panned);
  assert.equal(panned.x, panBefore.x - 140);
  assert.equal(panned.y, panBefore.y - 80);
  const afterPan = await savedBoard();
  assert.deepEqual(afterPan.cards.find(card => card.id === "reactnote"), noteBefore, "pan preserves card data");
  assert.equal(afterPan.view.x, panned.x, "pan camera persisted");
  observations.push("wheel pan updates the camera, preserves cards and saves the camera");
  await page.keyboard.down("Control");
  await page.mouse.wheel(0, -100);
  await page.keyboard.up("Control");
  await page.waitForTimeout(500);
  const zoomed = await page.evaluate(() => window.aegis?.canvas.view);
  assert.ok(zoomed && zoomed.z > panned.z, "pointer zoom");
  await page.evaluate(() => window.aegis?.canvas.setView({ x: 0, y: 0, z: 1 }));
  await page.waitForTimeout(500);
  const shell = page.locator('.card[data-id="reactnote"]');
  const rectangle = await shell.boundingBox();
  assert.ok(rectangle);
  await page.mouse.move(rectangle.x + rectangle.width / 2, rectangle.y + 6);
  await page.mouse.down();
  await page.mouse.move(rectangle.x + rectangle.width / 2 + 80, rectangle.y + 66, { steps: 6 });
  await page.mouse.up();
  await page.waitForFunction(before => {
    const card = window.aegis?.canvas.board.cards.find(card => card.id === "reactnote");
    return card !== undefined && (card.x !== before.x || card.y !== before.y);
  }, { x: noteBefore.x, y: noteBefore.y });
  await page.evaluate(async () => { await window.aegis?.flush(); });
  const dragged = (await savedBoard()).cards.find(card => card.id === "reactnote");
  assert.ok(dragged);
  assert.ok(dragged.x !== noteBefore.x || dragged.y !== noteBefore.y, "drag saved changed geometry");
  observations.push("pointer drag commits changed geometry");
  await note.fill("Typed and saved");
  await note.blur();
  await page.evaluate(async () => { await window.aegis?.flush(); });
  assert.equal((await savedBoard()).cards.find(card => card.id === "reactnote")?.text, "Typed and saved");
  const longText = Array.from({ length: 14 }, (_, index) => `Line ${index + 1}`).join("\n");
  await note.fill(longText);
  await note.blur();
  await page.waitForFunction(() => (window.aegis?.canvas.board.cards.find(card => card.id === "reactnote")?.h ?? 0) > 250);
  await page.evaluate(async () => { await window.aegis?.flush(); });
  assert.ok(((await savedBoard()).cards.find(card => card.id === "reactnote")?.h ?? 0) > 250, "typed note grows and saves its measured height");
  await page.evaluate(async () => { window.aegis?.undo(); await window.aegis?.flush(); });
  assert.equal((await savedBoard()).cards.find(card => card.id === "reactnote")?.text, "Typed and saved", "derived height shares the authored edit's Undo transaction");
  await page.evaluate(async () => { window.aegis?.redo(); await window.aegis?.flush(); });
  const typed = (await savedBoard()).cards.find(card => card.id === "reactnote");
  assert.equal(typed?.text, longText);
  assert.ok((typed?.h ?? 0) > 250, "Redo restores the saved measured height");
  observations.push("typing grows notes; derived measurement is part of the same Undo/Redo transaction");
  await page.reload();
  await page.waitForFunction(() => window.aegis?.canvas.board.cards.some(card => card.id === "reactnote"));
  assert.equal(await page.locator('.card[data-id="reactnote"] .body').innerText(), longText);
  assert.deepEqual((await savedBoard()).cards.find(card => card.id === "reactnote"), typed);
  observations.push("edited text and dragged position survive reload");
  await page.waitForTimeout(800);
  const frames = await page.evaluate(() => window.aegis?.canvas.inspect().frameCount);
  await page.waitForTimeout(300);
  assert.equal(await page.evaluate(() => window.aegis?.canvas.inspect().frameCount), frames, "idle stops animation frames");
  observations.push("idle schedules no scene frames");
  await page.screenshot({ path: join(output, "react-vertical-slice.png") });
});
writeFileSync(join(output, "react-vertical-slice.json"), JSON.stringify({ ok: true, observations }, null, 2) + "\n");
process.stdout.write(JSON.stringify({ ok: true, observations, output }) + "\n");
